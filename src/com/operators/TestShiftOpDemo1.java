package com.operators;

// shift operators << >> >>>
public class TestShiftOpDemo1 {

	public static void main(String[] args) {
		System.out.println("main method started");

		int a = 76;
		int b = 2;

		System.out.println(a << b);
		System.out.println(a >> b);
		System.out.println(a >>> b);
		// System.out.println(a <<< b);//CE
	}
	

}
